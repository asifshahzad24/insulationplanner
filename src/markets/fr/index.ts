/** Roll/pack/board row: thickness mm, declared R, m² per package, price per package. */
const t = (mm: number, r: number, m2: number, low: number, high = low): Thickness => ({
  mm,
  rSI: r,
  coverageM2: m2,
  price: { low, high },
  label: `R ${String(r).replace(".", ",")}`,
});

/** Loose-fill chart row: R, m² per bag, settled mm, installed mm. */
const row = (r: number, m2PerBag: number, settledMm: number, installedMm: number) => ({
  rSI: r,
  m2PerBag,
  settledMm,
  installedMm,
});

/** Price per package from a €/m² range (used where shops price by m²). */
const perM2 = (m2: number, low: number, high: number) => [Math.round(m2 * low * 100) / 100, Math.round(m2 * high * 100) / 100] as const;

